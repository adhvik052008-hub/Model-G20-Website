  /* ---- Projection ------------------------------------------------------ */
  /* Antarctica and the empty high Arctic are cropped; the remaining band
     gives a 1000 × 394 canvas with almost no dead space. */
  var LAT_MAX = 84;
  var LAT_MIN = -58;
  var VIEW_W = 1000;
  var VIEW_H = Math.round(VIEW_W * (LAT_MAX - LAT_MIN) / 360 * 100) / 100;

  function project(lon, lat) {
    return [
      (lon + 180) / 360 * VIEW_W,
      (LAT_MAX - lat) / (LAT_MAX - LAT_MIN) * VIEW_H
    ];
  }

  /* Even-odd ray casting across every ring of a shape. */
  function inRing(lon, lat, ring) {
    var inside = false, i, j, xi, yi, xj, yj;
    for (i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      xi = ring[i][0]; yi = ring[i][1];
      xj = ring[j][0]; yj = ring[j][1];
      if ((yi > lat) !== (yj > lat) &&
          lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
    return inside;
  }

  function isLand(lon, lat) {
    for (var s = 0; s < shapes.length; s++) {
      var rings = shapes[s].rings, hit = false;
      for (var r = 0; r < rings.length; r++) {
        if (inRing(lon, lat, rings[r])) hit = !hit;
      }
      if (hit) return true;
    }
    return false;
  }

  /* Sample the landmass into a dot lattice. Step is in degrees. */
  function sampleDots(step) {
    var dots = [], lon, lat, p;
    for (lat = LAT_MAX; lat >= LAT_MIN; lat -= step) {
      for (lon = -180; lon <= 180; lon += step) {
        if (!isLand(lon, lat)) continue;
        p = project(lon, lat);
        dots.push([Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10]);
      }
    }
    return dots;
  }

